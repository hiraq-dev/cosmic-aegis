import { Brain, Moon, Zap } from "lucide-react";
import { useStore } from "../lib/store";
import { buildAlerts, MOOD_LABEL, mentalRecommendations, mentalSummary } from "../lib/assess";
import { moodRows } from "../lib/chartData";
import { MoodCheckIn } from "../components/forms";
import { AlertsList } from "../components/AlertsList";
import { TrendBars, TrendLines } from "../components/charts";
import { DemoBadge, Disclaimer, Panel, Stat, StatusPill } from "../components/ui";

export default function Mental() {
  const { data } = useStore();
  const s = mentalSummary(data.moods);
  const rows = moodRows(data.moods);
  const alerts = buildAlerts(data).filter((a) => a.module === "mental");
  const recs = s.latest ? mentalRecommendations(s.latest) : [];

  return (
    <div className="space-y-6">
      <header>
        <div className="flex flex-wrap items-center gap-3">
          <h1 className="flex items-center gap-2 text-2xl font-bold text-white">
            <Brain className="text-aegis-violet" aria-hidden="true" /> Mental health monitoring
          </h1>
          <DemoBadge />
        </div>
        <p className="mt-1 max-w-3xl text-slate-300">
          Isolation, confinement and distance from home are among the main spaceflight hazards. A quick daily check-in helps you notice changes in mood, stress and sleep, and reminds you that support is available.
        </p>
      </header>

      {s.stressAlert && (
        <div role="alert" className="rounded-xl border border-review/50 bg-review/10 p-4 text-sm text-slate-100">
          <strong className="text-white">Repeated high stress noticed.</strong> {s.highStress} of your last 5 check-ins reported high stress. It may help to talk with your crew medical officer, a support clinician, or someone you trust back home.
        </div>
      )}

      <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
        <Stat label="Wellbeing score (demo)" value={`${s.score}/100`} sub="Average of last 3 check-ins" status={s.status} />
        <Stat label="Latest mood" value={s.latest ? MOOD_LABEL[s.latest.mood] : "-"} sub={s.latest ? `Stress ${s.latest.stress}/5` : "No check-ins yet"} />
        <Stat label="Average sleep" value={`${s.avgSleep.toFixed(1)} h`} sub="Last 7 entries" status={s.avgSleep < 6.5 ? "watch" : "nominal"} />
        <Stat label="Average fatigue" value={`${s.avgFatigue.toFixed(1)}/5`} sub="Last 7 entries (5 = exhausted)" />
      </div>

      <div className="grid gap-4 lg:grid-cols-[1fr_1.4fr]">
        <Panel title="Today's check-in">
          <MoodCheckIn />
        </Panel>
        <div className="space-y-4">
          <Panel title="Mood and stress trend" action={<DemoBadge />}>
            <TrendLines
              data={rows}
              domain={[1, 5]}
              label="Line chart of mood and stress over the last 14 days"
              series={[
                { key: "mood", label: "Mood (5 = excellent)", color: "#22d3ee" },
                { key: "stress", label: "Stress (5 = very high)", color: "#fb7185" },
              ]}
            />
          </Panel>
          <Panel title="Sleep" icon={<Moon size={16} aria-hidden="true" />}>
            <TrendBars data={rows} dataKey="sleep" name="Sleep (h)" color="#8b5cf6" label="Bar chart of hours slept over the last 14 days" height={150} />
          </Panel>
        </div>
      </div>

      <div className="grid gap-4 lg:grid-cols-2">
        <Panel title="Suggestions for today" icon={<Zap size={16} aria-hidden="true" />}>
          <ul className="space-y-2 text-sm text-slate-200">
            {recs.map((r) => (
              <li key={r}>- {r}</li>
            ))}
          </ul>
          <p className="mt-3 text-xs text-slate-400">General wellbeing tips only, generated by simple rules. They are not therapy or medical advice.</p>
        </Panel>
        <Panel title="Mental health alerts" action={<StatusPill status={s.status} />}>
          <AlertsList alerts={alerts} empty="No mental-health alerts. Keep checking in daily." />
        </Panel>
      </div>
      <Disclaimer />
    </div>
  );
}
